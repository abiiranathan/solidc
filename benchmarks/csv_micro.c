/*
 * csv_micro.c — parse and write throughput for the CSV library.
 *
 * Generates a deterministic mixed-content file (quoted fields containing
 * commas/escaped quotes plus plain and numeric fields), then measures:
 *   parse — full csv_reader_parse() including its row-counting pass.
 *   write — 500k rows through csvwriter_write_row().
 */

#include "../include/csvparser.h"

#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>

#define ROWS 500000

static uint64_t ns_now(void) {
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (uint64_t)ts.tv_sec * 1000000000ull + (uint64_t)ts.tv_nsec;
}

int main(void) {
    const char* dir = getenv("TMPDIR");
    if (!dir || !*dir) dir = "/tmp";

    char path[512], wpath[512], cmd[600];
    snprintf(path, sizeof path, "%s/csv_micro.csv", dir);
    snprintf(wpath, sizeof wpath, "%s/csv_micro_out.csv", dir);
    snprintf(cmd, sizeof cmd, "mkdir -p %s", dir);
    system(cmd);

    /* ── generate ─────────────────────────────────────────────────────── */
    FILE* f = fopen(path, "w");
    if (!f) return 1;
    for (int r = 0; r < ROWS; r++) {
        fprintf(f,
                "%d,name_%d_field,42.5,\"quoted, field %d\",true,2024-01-%02d,"
                "hello world,some text here,%d,3.14159,end_%d,padding padding padding %d\n",
                r, r, r, (r % 28) + 1, r % 1000, r % 100000, r);
    }
    fclose(f);

    printf("CSV Micro-Benchmarks (%d rows)\n", ROWS);

    /* ── parse ─────────────────────────────────────────────────────────── */
    uint64_t best = ~0ull;
    size_t rows = 0;
    for (int r = 0; r < 3; r++) {
        CsvReader* rd = csv_reader_new(path, 0);
        if (!rd) return 1;
        uint64_t t0 = ns_now();
        Row** rws = csv_reader_parse(rd);
        uint64_t d = ns_now() - t0;
        if (!rws) {
            fprintf(stderr, "parse failed\n");
            return 1;
        }
        rows = csv_reader_numrows(rd);
        if (d < best) best = d;
        csv_reader_free(rd);
    }
    double mb = (double)ROWS * 148.0 / 1e6; /* approx generated bytes per row */
    printf("  parse : %7.1f ms  (~%5.0f MB/s)  rows=%zu\n", best / 1e6, mb / ((double)best / 1e9), rows);

    /* ── write ─────────────────────────────────────────────────────────── */
    char* fields[12];
    for (int i = 0; i < 12; i++) fields[i] = malloc(32);
    for (int i = 0; i < 12; i++) snprintf(fields[i], 32, "value-%d,text", i);

    best = ~0ull;
    for (int r = 0; r < 3; r++) {
        CsvWriter* w = csvwriter_new(wpath);
        if (!w) return 1;
        uint64_t t0 = ns_now();
        for (int i = 0; i < ROWS; i++) csvwriter_write_row(w, (const char**)fields, 12);
        uint64_t d = ns_now() - t0;
        if (d < best) best = d;
        csvwriter_free(w);
    }
    printf("  write : %7.1f ms\n", best / 1e6);

    for (int i = 0; i < 12; i++) free(fields[i]);
    remove(path);
    remove(wpath);
    return 0;
}
